"""The blockchain: block application, fork resolution, reorg, and persistence.

This is the consensus core.  It owns the main chain (an in-memory list of
:class:`~block.Block`), the current :class:`~state.WorldState`, and a side-branch
store used for fork handling.  Consensus follows the *heaviest chain* rule:
when two competing branches exist, the one with greater cumulative work wins,
and the node re-organises onto it (rolling back blocks below the fork point and
re-applying the winning branch).

Persistence is per-block: ``blocks/NNNNNN.json`` holds a block and
``state/NNNNNN.json`` holds the world state *after* that height, both written
atomically and mirrored by a version ledger for rollback.

Damage tolerance / quarantine
-----------------------------
A corrupt or tampered block file no longer renders the whole chain unusable.
On startup the node loads the longest *linked, hash-consistent prefix* and
exposes everything beyond it through a per-block validation report
(:meth:`scan_blocks`), distinguishing:

* ``damaged``   — the block file itself fails verification (hash/PoW/merkle/
                  signature/missing or unreadable JSON);
* ``orphan``    — a sound file whose link to the active chain is broken by a
                  damaged ancestor;
* ``state_damaged`` — block file sound, state snapshot corrupt: the snapshot is
                  deterministically regenerated by replay on boot, so healthy
                  blocks stay online.

Operators can quarantine damaged blocks (files physically moved into the
reversible :class:`~quarantine.QuarantineStore`, healthy successors marked
``detached`` and kept), after which browsing and mining continue from the last
good block. Every operation is undoable; restoring onto a diverged chain
(mining already replaced the blocks) is refused rather than overwriting data.
"""

